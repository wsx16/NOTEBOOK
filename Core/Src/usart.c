/**
 * @brief  重定向 printf 到串口输出
 *         允许使用 printf() 函数通过 huart1 发送数据
 * @param  ch: 要发送的字符
 * @param  f:  文件指针 (未被使用)
 * @return 发送的字符
 */
int fputc(int ch, FILE *f) {
	uint8_t temp[1] = {ch};
	HAL_UART_Transmit(&huart1, temp, 1, 2); // 阻塞发送1个字节
	return ch;
}
